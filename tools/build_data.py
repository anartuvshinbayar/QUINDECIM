"""Pack soums.geojson and data.csv into one compact script, data.js, that index.html loads.

Browsers block fetch() when index.html is opened straight from disk (file://), so the site reads
its data from window.QUINDECIM_DATA instead. The CSV and GeoJSON stay the source of truth;
data.js is a smaller copy for the browser:

  window.QUINDECIM_DATA = {
    "format": 2, "sample": false,
    "soums":  [[soum_id, name_en, name_mn, aimag, geometry], ...],   # coordinates rounded to 0.01 degree
    "aimags": [[aimag, geometry], ...],                               # from aimags.geojson, if present
    "series": {variable: {soum_id: [first_year, value, value, ...]}}, # null for a missing year
    "grass":  {soum_id: [land_km2, grass_km2]}                         # from grassland.csv, if present
  }

Run this after any change to the data files (the export scripts do it for you).
Usage: python3 tools/build_data.py [folder]      (default: data/)
"""
import csv, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def _round(c, nd=2):
    if isinstance(c[0], list):
        return [_round(x, nd) for x in c]
    return [round(c[0], nd), round(c[1], nd)]


def _dedupe(ring):
    """Drop consecutive points that became identical after rounding."""
    out = []
    for p in ring:
        if not out or p != out[-1]:
            out.append(p)
    return out


def _geometry(g):
    coords = _round(g["coordinates"])
    if g["type"] == "Polygon":
        coords = [_dedupe(r) for r in coords]
    else:
        coords = [[_dedupe(r) for r in poly] for poly in coords]
    return {"type": g["type"], "coordinates": coords}


def build(folder=None):
    folder = pathlib.Path(folder).resolve() if folder else ROOT / "data"
    geo = json.loads((folder / "soums.geojson").read_text())
    soums = []
    for f in geo["features"]:
        p = f["properties"]
        soums.append([str(p["soum_id"]), p.get("name_en") or "", p.get("name_mn") or "", p.get("aimag") or "",
                      _geometry(f["geometry"])])

    raw = {}
    with open(folder / "data.csv") as fh:
        for r in csv.DictReader(fh):
            v = r["value"]
            raw.setdefault(r["variable"], {}).setdefault(r["soum_id"], {})[int(r["year"])] = float(v) if v != "" else None
    series = {}
    for var, by_soum in raw.items():
        series[var] = {}
        for sid, years in by_soum.items():
            y0, y1 = min(years), max(years)
            vals = [years.get(y) for y in range(y0, y1 + 1)]
            vals = [int(x) if x is not None and x == int(x) and var == "first_frost" else x for x in vals]
            series[var][sid] = [y0] + vals

    aimags = []
    if (folder / "aimags.geojson").exists():
        for f in json.loads((folder / "aimags.geojson").read_text())["features"]:
            aimags.append([f["properties"]["aimag"], _geometry(f["geometry"])])

    # Greenness is measured on grassland only: each soum's land and grassland area, so the site can say how much of
    # the soum the value covers (and why a soum with almost no grassland has no greenness value).
    grass = {}
    if (folder / "grassland.csv").exists():
        with open(folder / "grassland.csv") as fh:
            for r in csv.DictReader(fh):
                grass[r["soum_id"]] = [round(float(r["land_km2"])), round(float(r["grass_km2"]), 1)]

    out = folder / "data.js"
    payload = {"format": 2, "sample": geo.get("sample") is True, "soums": soums, "aimags": aimags, "series": series}
    if grass:
        payload["grass"] = grass
    out.write_text(
        "// Generated by tools/build_data.py from soums.geojson and data.csv. Do not edit by hand.\n"
        "window.QUINDECIM_DATA=" + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"
    )
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size / 1e6:.2f} MB")


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else None)
